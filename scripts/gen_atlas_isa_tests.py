"""Generate the C harness of each Atlas ISA-level baremetal test (atlas/isa builds them).

CREDIT: the sources are the Atlas team's (tapeout-chipyard 48c3a7d, sp26-atlas-acc 2ae0bef209df,
baremetal/; authors in third_party/tapeout-chipyard/NOTICE and AUTHORS-*.txt). The idea of importing
the team's assembler.py as a module and replacing their Makefile rule with a script, and the generator
lookup / cwd convention, follow scripts/atlas/gen_atlas_tests.py of ucb-bar/Baremetal-IDE PR #65
(author Crackle07, head 0a22f5a820ca). Unlike that script, the harness text is NOT re-implemented:
it is whatever assembler.py's emit_c_file() emits (printf, "*** PASSED ***"/"*** FAILED ***", return
code), so the test is the team's own harness; this script only reproduces baremetal/Makefile's rule
`$(TESTS_DIR)/atlas_%.c: $(ASM_DIR)/%.S`:

    gen_<name>.py exists            -> python gen_<name>.py > <name>.json ; assembler.py <name>.S --out-c --golden-json
    else gen_<name mxu[01]_->mxu_>  -> same with that generator
    else                            -> assembler.py <name>.S --out-c      (inline @DRAM/@CHECK_DRAM only)

The generator runs with cwd = baremetal/ (as in the Makefile) and the repo's .venv python (torch, numpy,
numba: requirements-atlas.txt). Nothing is written into the (read-only) source tree: golden JSON and
numba caches go to --json-dir / a cache dir below --out-dir.

usage:
  gen_atlas_isa_tests.py --atlas-dir <.../sp26-atlas-acc/baremetal> --list
  gen_atlas_isa_tests.py --atlas-dir DIR --out-dir DIR [--json-dir DIR] [--python PY] (--all | NAME...) [-j N]
"""
import argparse
import concurrent.futures
import glob
import os
import re
import subprocess
import sys


SAMPLE_HEAD = """# SPDX-License-Identifier: Apache-2.0
# GENERATED by: scripts/gen_atlas_isa_tests.py --atlas-dir third_party/tapeout-chipyard/generators/sp26-atlas-acc/baremetal --emit-sample-yaml
# One scenario per Atlas ISA-level baremetal test (baremetal/assembly/*.S, 121) and board variant.
# Build-only: plain Spike has no Atlas (see the README for running them with the Atlas Spike model).
# run_tests.py builds only the board it is given, so the vcu118_ta scenarios SKIP on the default board.
sample:
  name: atlas_isa
common:
  tags: atlas hardware atlas_isa
  build_only: true
  timeout: 900
tests:
"""


def list_tests(atlas_dir):
    # Same set as the Makefile: $(wildcard $(ASM_DIR)/*.S), top level only
    # (assembly/saturn_atlas_cooperative/ holds the host-driven kernels of the saturn_atlas_* tests).
    return sorted(os.path.splitext(os.path.basename(p))[0]
                  for p in glob.glob(os.path.join(atlas_dir, "assembly", "*.S")))


def find_generator(atlas_dir, name):
    gen_dir = os.path.join(atlas_dir, "generators")
    for base in (name, re.sub(r"mxu[01]_", "mxu_", name)):   # Makefile: sed -E 's/mxu[01]_/mxu_/'
        cand = os.path.join(gen_dir, f"gen_{base}.py")
        if os.path.isfile(cand):
            return cand
    return None


def gen_one(atlas_dir, out_dir, json_dir, python, name):
    sys.dont_write_bytecode = True
    sys.path.insert(0, atlas_dir)
    import assembler   # the team's, unmodified

    src_path = os.path.join(atlas_dir, "assembly", name + ".S")
    with open(src_path) as f:
        source = f.read()
    code = assembler.assemble(source)
    beat_bytes = 32   # assembler.py default
    golden = None
    gen = find_generator(atlas_dir, name)
    note = "standalone"
    if gen:
        os.makedirs(json_dir, exist_ok=True)
        jpath = os.path.join(json_dir, name + ".json")
        env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1",
                   NUMBA_CACHE_DIR=os.path.join(out_dir, ".numba-cache"))
        with open(jpath, "w") as jf:
            r = subprocess.run([python, gen], cwd=atlas_dir, env=env, stdout=jf,
                               stderr=subprocess.PIPE, text=True)
        if r.returncode != 0:
            raise RuntimeError(f"{os.path.basename(gen)} failed (rc={r.returncode}):\n{r.stderr[-2000:]}")
        dram_base = assembler._parse_dram_base(source)
        if dram_base is None:
            dram_base = 0
        golden = assembler._parse_golden_json(jpath, dram_base, beat_bytes)
        note = os.path.basename(gen)
    else:
        inline = assembler._parse_inline_golden(source, beat_bytes)
        if inline is not None:
            _, pa, pw, ca, cw = inline
            golden = (pa, pw, ca, cw)
            note = "inline golden"
    macs0, macs1 = assembler._parse_perf_macs(source)
    c = assembler.emit_c_file(code, name, golden=golden,
                              perf_threshold=assembler._parse_perf_threshold(source),
                              perf_report=assembler._parse_perf_report(source),
                              perf_macs_mxu0=macs0, perf_macs_mxu1=macs1)
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, f"atlas_{name}.c")
    tmp = out + ".tmp"
    with open(tmp, "w") as f:
        f.write(c)
    os.replace(tmp, out)
    return name, len(code), note


def _job(a):
    try:
        return gen_one(*a) + (None,)
    except Exception as e:   # reported per test, the caller decides
        return a[-1], 0, "", f"{type(e).__name__}: {e}"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--atlas-dir", required=True, help="sp26-atlas-acc/baremetal")
    ap.add_argument("--out-dir")
    ap.add_argument("--json-dir")
    ap.add_argument("--python", default=sys.executable, help="python for the generators (needs torch, numpy, numba)")
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--emit-sample-yaml", action="store_true",
                    help="print atlas/isa/sample.yaml (one scenario per test and board)")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("-j", type=int, default=1)
    ap.add_argument("names", nargs="*")
    a = ap.parse_args()
    atlas_dir = os.path.abspath(a.atlas_dir)
    if a.list:
        print("\n".join(list_tests(atlas_dir)))
        return 0
    if a.emit_sample_yaml:
        print(SAMPLE_HEAD, end="")
        for n in list_tests(atlas_dir):
            for plat, tag in (("chipyard_penguin/penguin", "penguin"), ("chipyard_penguin/penguin/vcu118_ta", "penguin.vcu118_ta")):
                print(f"  sample.{tag}.atlas_isa.{n}:\n    platform_allow: {plat}\n    extra_args: ATLAS_ISA_TEST={n}")
        return 0
    if not a.out_dir:
        ap.error("--out-dir required")
    out_dir = os.path.abspath(a.out_dir)
    json_dir = os.path.abspath(a.json_dir or os.path.join(out_dir, "json"))
    names = list_tests(atlas_dir) if a.all else a.names
    unknown = [n for n in names if n not in set(list_tests(atlas_dir))]
    if unknown or not names:
        print(f"error: unknown or no tests: {unknown}", file=sys.stderr)
        return 2
    jobs = [(atlas_dir, out_dir, json_dir, a.python, n) for n in names]
    bad = 0
    with concurrent.futures.ProcessPoolExecutor(max_workers=max(1, a.j)) as ex:
        for name, n, note, err in ex.map(_job, jobs):
            if err:
                bad += 1
                print(f"FAIL {name}: {err}", file=sys.stderr)
            else:
                print(f"ok   {name}: {n} instructions ({note})")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
